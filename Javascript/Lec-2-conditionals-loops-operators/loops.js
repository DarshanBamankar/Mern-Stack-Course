// For Loop

// with -> 1) Post Increment - i++
//         2) Post Decrement - i--

    for(let i = 0; i<10; i++){
        console.log(i);
    }

// While Loop

    let j = 0;

    while(j < 5){
        console.log(j);
        j++;
    }

// Do While

    let k = 0;

    do{
        console.log(k);
        k++;
    }
    while(k<5);

// if-else condition

    let userAge = 21;

    if(userAge >= 18){
        console.log("You're eligible");
    }
    else{
        console.log("Sorry, Your not Eligible");
    }

// if-elif-else condition

    let myAge = 20;

    if(myAge < 18){
        console.log("Displaying children ");
    }
    else if(myAge > 60){
        console.log("Displaying old ");
    } // Multiple else if conditions can be taken
    else{
        console.log("Displaying Adult ")
    };


    
